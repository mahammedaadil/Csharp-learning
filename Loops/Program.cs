//while loop 
int a = 0;
while (a <= 10)
{
    Console.WriteLine(a);
    a++;
}  //check condition first

int b = 10;

//do-while
do
{
    Console.WriteLine(b);
    b++; 
} while (b <= 10); //atleast execute one time,check condition at last


//for loop

for(int i = 0; i <= 10; i++)
{
    Console.WriteLine(i);
} //mostly used for arrays